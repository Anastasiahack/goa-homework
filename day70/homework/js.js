switch (question ? question.toLowerCase().trim() : "") {
    case "ბექენდი":
    case "ბექენდის ენა":
        console.log("ბექენდის (სერვერული) პოპულარული ენებია: Node.js (JavaScript), Python, PHP, Java, C#.");
        break;

    case "ფრონტენდი":
    case "ფრონტენდის ენა":
        console.log("ფრონტენდის მთავარი ინტერაქტიული ენა არის JavaScript.");
        break;

    case "მარკირება":
    case "მარკირების ენა":
        console.log("ვების ძირითადი მარკირების ენა არის HTML (HyperText Markup Language).");
        break;

    case "სტილები":
    case "დიზაინი":
    case "დიზაინის ენა":
        console.log("ვებ-გვერდის დიზაინისა და ვიზუალის სტილების ენა არის CSS (Cascading Style Sheets).");
        break;

    case "მონაცემთა ბაზა":
    case "ბაზების ენა":
        console.log("მონაცემთა ბაზებთან სამუშაო ენა არის SQL (მაგ: PostgreSQL, MySQL).");
        break;

    default:
        console.log(" ეს კატეგორია ვერ მოიძებნა. გთხოვთ ჩაწეროთ: ბექენდი, ფრონტენდი, მარკირება ან დიზაინი.");
        break;
}

