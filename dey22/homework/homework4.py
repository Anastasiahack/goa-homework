#**if/else Statements**
# 4)მომხმარებელს შემოატანინეთ რიცხვი , თქვენი მიზანია გაიგოთ ეს რიცხვი დადებითია , უარყოფითია თუ ნულის ტოლია


num = float(input("შეიყვანე რიცხვი: "))

if num > 0:
    print("რიცხვი დადებითია")
elif num < 0:
    print("რიცხვი უარყოფითია")
else:
    print("რიცხვი ნულის ტოლია")